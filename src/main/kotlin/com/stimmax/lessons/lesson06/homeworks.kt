// 6. Создайте функцию, которая конвертирует температуру из градусов Цельсия в Фаренгейты и наоборот в зависимости от указанной единицы измерения (C/F). Единицу измерения нужно передать вторым аргументом функции. Несколько аргументов передаются через запятую. Распечатай в консоль результат конвертации с добавлением единицы измерения. Чтобы добавить единицу измерения после результата используй функцию печати без переноса строки print("C") или print("F").

fun task6(arg1: Double, arg2: Char){
    when(arg2){
        // Формула конвертации из C в F: (C * 9/5) + 32
        'C' -> {
            val F = (arg1 * 9 / 5) + 32
            print(F)
            print("F")
        }
        'F' -> {
            // Формула конвертации из F в C: (F - 32) * 5/9
            val C = (arg1 - 32) * 5 / 9
            print(C)
            print("C")
        }
        else -> {
            println("Неверный ввод")
        }

    }
}



// 7. Напишите функцию, которая на основе температуры воздуха рекомендует тип одежды: "куртка и шапка" при температуре ниже +10, "ветровка" от +10 до +18 градусов включительно и "футболка и шорты" при температуре выше +18 градусов. При температурах ниже -30 и выше +35 рекомендуйте не выходить из дома.



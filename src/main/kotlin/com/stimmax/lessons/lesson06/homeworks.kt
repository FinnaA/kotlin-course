    }
}

//4. Клиенты интернет-магазина получают бонусные баллы за покупки. Напишите функцию, которая принимает сумму покупки и печатает в консоль количество бонусных баллов: 2 балла за каждые 100 рублей при сумме покупки до 1000 рублей и 3 балла за каждые 100 рублей при сумме свыше этого.

fun task4(arg: Double) {
    when {
        arg < 0 -> println("Сумма покупки не может принимать отрицательные значения")
        arg <= 1000.0 -> { // Double поэтому через точку и с нулем
            val points = (arg / 100) * 2
            println(points)
        }
        else -> {
            val points = (arg / 100) * 3
            println(points)
        }
    }
}

